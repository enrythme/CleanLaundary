SET LOCAL password_encryption = 'scram-sha-256';
CREATE TABLE users (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    login varchar(40) NOT NULL UNIQUE CHECK (login ~ '^[A-Za-z0-9_.-]{3,40}$'),
    full_name varchar(100) NOT NULL CHECK (length(trim(full_name)) BETWEEN 2 AND 100),
    email varchar(150) NOT NULL UNIQUE CHECK (email ~ '^[^[:space:]@]+@[^[:space:]@]+[.][^[:space:]@]+$'),
    password_hash varchar(200) NOT NULL CHECK (password_hash ~ '^150000:[A-Za-z0-9+/=]+:[A-Za-z0-9+/=]+$'),
    role varchar(5) NOT NULL DEFAULT 'User' CHECK (role IN ('User','Admin')),
    theme varchar(5) NOT NULL DEFAULT 'Light' CHECK (theme IN ('Light','Dark')),
    failed_attempts integer NOT NULL DEFAULT 0 CHECK (failed_attempts BETWEEN 0 AND 100),
    active boolean NOT NULL DEFAULT true
);
CREATE TABLE services (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(120) NOT NULL UNIQUE CHECK (length(trim(name)) BETWEEN 2 AND 120),
    unit varchar(2) NOT NULL CHECK (unit IN ('шт','кг')),
    price numeric(8,2) NOT NULL CHECK (price BETWEEN 1 AND 100000),
    active boolean NOT NULL DEFAULT true
);
CREATE TABLE orders (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    service_id integer NOT NULL REFERENCES services(id) ON DELETE CASCADE,
    branch varchar(20) NOT NULL CHECK (branch IN ('Центральный','Северный','Южный')),
    received_date date NOT NULL,
    due_date date NOT NULL CHECK (due_date >= received_date AND due_date <= received_date + 365),
    quantity numeric(6,3) NOT NULL CHECK (quantity BETWEEN 0.001 AND 100),
    unit_price numeric(8,2) NOT NULL CHECK (unit_price BETWEEN 1 AND 100000),
    total numeric(10,2) GENERATED ALWAYS AS (round(quantity * unit_price,2)) STORED,
    status varchar(10) NOT NULL DEFAULT 'Принят' CHECK (status IN ('Принят','В работе','Готов','Выдан')),
    description varchar(250) NOT NULL CHECK (length(trim(description)) BETWEEN 2 AND 250)
);
CREATE INDEX orders_user_id_idx ON orders(user_id);
CREATE INDEX orders_service_id_idx ON orders(service_id);
CREATE INDEX orders_status_idx ON orders(status);
